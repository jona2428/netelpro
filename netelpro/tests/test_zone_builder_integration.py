"""Integration tests: zone-rule BUILDER vs reference Python generator.

The heart of Session 3 (auto-hosting): the compiled Netelpro builder
(builders/zone_rule_builder.sl) must produce byte-identical rule source
to the Python reference generator -- except the provenance line, which
honestly names the builder as author.

Also verifies: the builder's product compiles natively as a gate rule,
makes correct decisions (including the src_backup component-wise trap),
and that the adapter enforces capacity + fail-safe behavior.
"""

